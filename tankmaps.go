/* ---------- помощники ---------- */

func border(m string, hx, hz, h float64) []MBox {
	return []MBox{bx(m, -hx-1, -3, -hz-1, hx+1, h, -hz), bx(m, -hx-1, -3, hz, hx+1, h, hz+1),
		bx(m, -hx-1, -3, -hz, -hx, h, hz), bx(m, hx, -3, -hz, hx+1, h, hz)}
}

// blk — сплошной блок на земле (плато, холм).
func blk(m string, x0, z0, x1, z1, h float64) MBox { return bx(m, x0, 0, z0, x1, h, z1) }

// bld — здание: коробка и крыша-карниз.
func bld(m string, x0, z0, x1, z1, y, h float64) []MBox {
	return []MBox{bx(m, x0, y, z0, x1, y+h, z1), bx("roof", x0-.25, y+h, z0-.25, x1+.25, y+h+.35, z1+.25)}
}

// deck — мост на высоте y с перилами вдоль длинной стороны.
func deck(m string, x0, z0, x1, z1, y float64) []MBox {
	out := []MBox{bx(m, x0, y-.4, z0, x1, y, z1)}
	if x1-x0 > z1-z0 {
		out = append(out, bx("trim", x0, y, z0, x1, y+1.1, z0+.3), bx("trim", x0, y, z1-.3, x1, y+1.1, z1))
	} else {
		out = append(out, bx("trim", x0, y, z0, x0+.3, y+1.1, z1), bx("trim", x1-.3, y, z0, x1, y+1.1, z1))
	}
	return out
}

func pillar(m string, x, z, h, r float64) MBox { return bx(m, x-r, 0, z-r, x+r, h, z+r) }

func crates(b []MBox, pts ...[2]float64) []MBox {
	for i, c := range pts {
		x, z := c[0], c[1]
		b = append(b, bx("crate", x, 0, z, x+2, 2, z+2))
		if i%2 == 0 {
			b = append(b, bx("crate", x+2.1, 0, z+.2, x+3.7, 1.6, z+1.8), bx("crate", x+.3, 2, z+.3, x+1.8, 3.5, z+1.8))
		}
	}
	return b
}

// sp — точка возрождения лицом к центру карты.
func sp(x, y, z float64, team int) TSpawn { return TSpawn{V3{x, y, z}, math.Atan2(x, z), team} }

func mkTheme(name string, bound float64, sky, zen, amb, sun, sunc V3, fog float64) Theme {
	return Theme{Name: name, Sky: sky, Zen: zen, Fog: fog, Amb: amb, Sun: sun, SunC: sunc, Bound: bound, FloorMin: -3, lavaY: -1000}
}

func dayTheme(name string, bound float64) Theme {
	return Theme{Name: name, Sky: V3{.78, .84, .9}, Zen: V3{.33, .54, .86}, Fog: .0055, Amb: V3{.5, .5, .5},
		Sun: V3{-.4, -1, -.32}, SunC: V3{.82, .74, .6}, Bound: bound, FloorMin: -3, lavaY: -1000}
}

