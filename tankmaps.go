/* ---------- флаги, точки и места для ящиков: считаются по геометрии карты ---------- */

var noDrop = map[string]bool{"water": true, "trim": true, "crate": true, "leaves": true, "roof": true, "bark": true}

func boxTop(b *MBox, x, z float64) float64 {
	if b.R == 0 {
		return b.B[4]
	}
	ax := 0
	if b.R >= 3 {
		ax = 2
	}
	v := x
	if ax == 2 {
		v = z
	}
	f := (v - b.B[ax]) / (b.B[ax+3] - b.B[ax])
	if b.R%2 == 0 {
		f = 1 - f
	}
	return b.B[1] + (b.B[4]-b.B[1])*math.Max(0, math.Min(1, f))
}

// surf: самая верхняя поверхность в точке и её материал.
func (m *TMap) surf(x, z float64) (float64, string, bool) {
	best, mat := -1e9, ""
	for i := range m.boxes {
		b := &m.boxes[i]
		if x < b.B[0] || x > b.B[3] || z < b.B[2] || z > b.B[5] {
			continue
		}
		if t := boxTop(b, x, z); t > best {
			best, mat = t, b.M
		}
	}
	return best, mat, best > -100
}

func (m *TMap) zones() {
	bound := m.theme.Bound - 2.5
	cands := []V3{}
	for x := -bound; x <= bound; x += 3 {
		for z := -bound; z <= bound; z += 3 {
			y, mat, ok := m.surf(x, z)
			if !ok || noDrop[mat] || y > 7.6 || y < -.5 {
				continue
			}
			flat := true
			for k := 0; k < 8 && flat; k++ {
				a := float64(k) * math.Pi / 4
				y2, mat2, ok2 := m.surf(x+2.4*math.Cos(a), z+2.4*math.Sin(a))
				flat = ok2 && !noDrop[mat2] && math.Abs(y2-y) < .3
			}
			if flat {
				cands = append(cands, V3{x, y, z})
			}
		}
	}
	if len(cands) == 0 {
		return
	}
	nearest := func(p V3, horiz bool, skip func(V3) bool) V3 {
		best, bd := cands[0], 1e18
		for _, c := range cands {
			if skip != nil && skip(c) {
				continue
			}
			d := c.sub(p)
			if horiz {
				d[1] = 0
			}
			if l := d.dot(d); l < bd {
				best, bd = c, l
			}
		}
		return best
	}
	for t := 1; t <= 2; t++ {
		if m.flags[t] != (V3{}) {
			continue
		}
		var c V3
		n := 0.0
		for _, s := range m.spawns {
			if s.Team == t {
				c = c.add(s.P)
				n++
			}
		}
		if n > 0 {
			m.flags[t] = nearest(c.mul(1/n), false, nil)
		}
	}
	far := func(c V3) bool {
		for t := 1; t <= 2; t++ {
			if near(c, m.flags[t], 10, 99) {
				return true
			}
		}
		for _, q := range m.cps {
			if near(c, q, 12, 99) {
				return true
			}
		}
		return false
	}
	a, bb := m.flags[1], m.flags[2]
	for _, f := range []float64{.5, .22, .78} {
		m.cps = append(m.cps, nearest(a.add(bb.sub(a).mul(f)), true, far))
	}
	m.cps[0], m.cps[1] = m.cps[1], m.cps[0] // порядок A, B, C от красных к синим
	// места для ящиков: равномерно по карте
	m.drops = []V3{nearest(V3{}, true, nil)}
	for len(m.drops) < 26 && len(m.drops) < len(cands) {
		best, bd := cands[0], -1.0
		for _, c := range cands {
			md := 1e18
			for _, d := range m.drops {
				v := c.sub(d)
				md = math.Min(md, v.dot(v))
			}
			if md > bd {
				best, bd = c, md
			}
		}
		m.drops = append(m.drops, best)
	}
}

